const express = require('express');
const router = express.Router();
const ctrl = require('../controllers/thuoc.controller');
const auth = require('../middlewares/auth.middleware');
const { webOnlyWrite } = require('../middlewares/mobile-scope.middleware');
const { checkPermission } = require('../middlewares/permission.middleware');
router.use(auth);
router.get('/',    checkPermission('QLTHUOC', 'xem'), ctrl.getAll);
router.get('/:id', checkPermission('QLTHUOC', 'xem'), ctrl.getById);
router.post('/',   webOnlyWrite, checkPermission('QLTHUOC', 'them'), ctrl.create);
router.put('/:id', webOnlyWrite, checkPermission('QLTHUOC', 'sua'), ctrl.update);
router.delete('/:id', webOnlyWrite, checkPermission('QLTHUOC', 'xoa'), ctrl.remove);
module.exports = router;
