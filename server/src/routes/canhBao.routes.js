const express = require('express');
const router = express.Router();
const ctrl = require('../controllers/canhBao.controller');
const auth = require('../middlewares/auth.middleware');
const { loadMobileScope, guardResource, caregiverOnlyWrite } = require('../middlewares/mobile-scope.middleware');
const { checkPermission } = require('../middlewares/permission.middleware');
router.use(auth);
router.use(loadMobileScope);
router.get('/', checkPermission('QLCANHBAO', 'xem'), ctrl.getAll);
router.patch('/:id/seen', caregiverOnlyWrite, checkPermission('QLCANHBAO', 'sua'), guardResource('CanhBao', 'CanhBaoID'), ctrl.markSeen);
router.patch('/:id/resolve', caregiverOnlyWrite, checkPermission('QLCANHBAO', 'sua'), guardResource('CanhBao', 'CanhBaoID'), ctrl.resolve);
module.exports = router;
