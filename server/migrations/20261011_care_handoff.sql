-- Internal caregiver information: never store in the elderly-visible journal.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID('dbo.BanGiaoChamSoc','U') IS NULL
BEGIN
 CREATE TABLE dbo.BanGiaoChamSoc(
  ID INT IDENTITY PRIMARY KEY,NguoiCaoTuoiID INT NOT NULL REFERENCES dbo.HoSoNguoiCaoTuoi(NguoiCaoTuoiID),
  NguoiTaoID INT NOT NULL REFERENCES dbo.NguoiDung(UserID),
  DaLam NVARCHAR(1000) NOT NULL,ConCho NVARCHAR(1000) NOT NULL,LuuY NVARCHAR(1000) NOT NULL,
  PhienBan INT NOT NULL DEFAULT 1,RequestID VARCHAR(64) NOT NULL,DauVao NVARCHAR(MAX) NOT NULL,
  NgayTao DATETIME2 NOT NULL DEFAULT DATEADD(HOUR,7,SYSUTCDATETIME()),
  NgaySua DATETIME2 NOT NULL DEFAULT DATEADD(HOUR,7,SYSUTCDATETIME()),
  CONSTRAINT UQ_BanGiao_Request UNIQUE(NguoiTaoID,RequestID),CHECK(PhienBan>0)
 );
 CREATE TABLE dbo.LichSuBanGiao(
  ID INT IDENTITY PRIMARY KEY,BanGiaoID INT NOT NULL REFERENCES dbo.BanGiaoChamSoc(ID),
  PhienBan INT NOT NULL,NguoiSuaID INT NOT NULL REFERENCES dbo.NguoiDung(UserID),
  ThoiDiem DATETIME2 NOT NULL DEFAULT DATEADD(HOUR,7,SYSUTCDATETIME()),DuLieu NVARCHAR(MAX) NOT NULL,
  CONSTRAINT UQ_LichSuBanGiao UNIQUE(BanGiaoID,PhienBan)
 );
 CREATE TABLE dbo.DocBanGiao(
  BanGiaoID INT NOT NULL REFERENCES dbo.BanGiaoChamSoc(ID),
  NguoiDocID INT NOT NULL REFERENCES dbo.NguoiDung(UserID),
  PhienBan INT NOT NULL,ThoiDiem DATETIME2 NOT NULL DEFAULT DATEADD(HOUR,7,SYSUTCDATETIME()),
  CONSTRAINT PK_DocBanGiao PRIMARY KEY(BanGiaoID,NguoiDocID,PhienBan)
 );
 CREATE INDEX IX_BanGiao_ProfileDate ON dbo.BanGiaoChamSoc(NguoiCaoTuoiID,NgayTao);
END;
COMMIT;
